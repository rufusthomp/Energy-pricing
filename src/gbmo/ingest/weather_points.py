"""Which points stand in for each panel zone's wind and solar fleets, and why.

The hand-curated modelling layer for the weather instrument, sitting alongside `zones.py`
the way `weather_location` sits alongside `fuel`: nothing here is observed, it is all
choice, kept in one place so the choices are reviewable and auditable against a map.

## Why points, not a zone-average grid cell

A referee asked for an instrument built from actual weather rather than a TSO forecast.
An instrument is only as good as its correspondence with where the fleet actually sits:
averaging a bidding zone's bounding box would blend wind-farm coastlines with empty
interior and dilute the signal the treatment is supposed to isolate. So each zone gets a
handful of named points, chosen to sit on or near its principal wind areas (onshore
clusters, and offshore clusters where the zone has material offshore capacity) and its
principal solar and demand areas. Weights are equal and aggregation is a query-time
choice, exactly as `weather_location` and `commodity_price` keep their combination rules
out of the data.

## Split countries

Several zones split a country and the point selection is the thing that has to get that
right or the instrument is measuring the wrong country's weather:

- `DK_1` is Jutland and Funen (west, continental-synchronous); `DK_2` is Zealand and
  Bornholm (east, Nordic-synchronous). They clear at different prices most days.
- `SE_3` is central/southern Sweden including Stockholm and Gothenburg; `SE_4` is the
  southernmost tip (Skane), price-separated and windier.
- `NO_2` is the southwest corner of Norway, not the whole country.
- `IT_NORD` is northern Italy only.
- `DE_LU` is Germany plus Luxembourg as one zone since 2018-10-01: a Luxembourg point is
  kept even though it carries little weight, so the zone's second country is represented.

## Roles

`wind`, `solar` or `both`. A demand-centre point with no material generation nearby is
still tagged (usually `both`, since demand areas mix rooftop solar with imported wind):
the tag is a navigation aid for later aggregation choices, not a claim about installed
capacity at that pixel.
"""

