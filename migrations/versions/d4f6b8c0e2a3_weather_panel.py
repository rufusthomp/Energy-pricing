"""weather panel

A referee asked for an instrument built from actual weather rather than the TSO forecast
wind and solar penetration the paper's treatments already use. This adds a second, wider
weather layer for the European panel: hourly ERA5 reanalysis wind speed at 100m and
shortwave radiation at points chosen to sit on or near each zone's wind and solar fleets.

## A fifth schema, not more rows in `gb.weather`

`gb.weather` is long (`datetime, location, variable, value, unit`) because GB has five
points and three variables, so long stays small and keeps the combination rule (how the
points aggregate into a national proxy) in the query. The panel is 19 zones and roughly
5-8 points each: about 105 points, two variables, hourly, over ~7.8 years is on the order
of 105 * 2 * 68,000 hours =~ 14.3M rows long, against ~7.1M wide (one row per point-hour,
two value columns). That halving is the same trade `entsoe.generation` already made, and
the same justification applies: the raw Open-Meteo response for a point-year is cached
unaggregated to `data/raw/weather_panel/`, so changing which variables are stored, or
splitting wind and radiation back into long rows, is a reload of the cache, not a
re-fetch. See `docs/conventions.md`.

It is a new schema (`weather`) rather than new tables bolted onto `gb` or `entsoe`
because this data belongs to neither: it is not GB-specific (`gb`), and it is not an
ENTSO-E series (`entsoe`) -- it is a third source (Open-Meteo reanalysis) covering the
panel's footprint. A `weather.point` dimension keyed on `zone_id` sits alongside
`ref.zone` the way `weather_location` sits alongside `ref.fuel`: hand-curated modelling
choices, not observed facts, and reviewable as such. `weather.observation` is the
observed fact table.

## Units and the radiation convention

`wind_speed_100m` is km/h, matching `gb.weather`'s `wind_speed_100m` variable so the two
pipelines stay comparable without a conversion. `shortwave_radiation` is W/m2, and is
Open-Meteo's *mean over the preceding hour*: the value stamped at hour H is the average
instantaneous irradiance between H-1 and H, not an instantaneous reading at H. That
matches how the hourly grain is used everywhere else in this schema (a hydro or wind
generation figure for hour H is already a period average, never an instant), but it is
worth stating explicitly here since shortwave radiation is the one variable in this
database where "average over the hour" versus "reading at the hour" would otherwise be
ambiguous.

## No foreign key to `entsoe.calendar`

Same reasoning as `a305783f9fcc`: weather is an independent observation series and must
survive a panel rebuild. `entsoe`'s fact tables are truncated and reloaded by
`load_zones.py` on every run; a foreign key from `weather.observation` into anything in
`entsoe` would make that truncation cascade into data that took days to fetch.

Revision ID: d4f6b8c0e2a3
Revises: c3e5a7b9d1f2
Create Date: 2026-09-29
"""

