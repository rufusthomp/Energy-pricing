"""arbitrage tables

Five tables for the battery arbitrage study: two dimensions describing the asset and
the strategy, a run record, and two facts holding what a run produced.

Model outputs are the second sanctioned exception to the no-derived-data rule, for two
distinct reasons. Learned strategies (LSTM, RL) are not recomputable at all: they depend
on trained weights, a seed and a horizon, none of which the database holds. Deterministic
strategies (perfect-foresight LP, naive heuristic) are perfectly recomputable but not
affordably so, since re-solving an optimisation over ~300k settlement periods is not a
query-time computation in any useful sense. Both are observations *of a run*.

Profit is deliberately absent. It is a join of `dispatch` against `price`, so under the
convention it must be computed rather than stored. Store what a run did; compute what it
earned.

Revision ID: f75c7e384d2f
Revises: ed7e02dcf29d
Create Date: 2026-09-02
"""

