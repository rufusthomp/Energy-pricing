"""bidding zone panel

The cross-country layer. Hourly day-ahead price, load and aggregated generation for a
curated set of European bidding zones, sourced from the ENTSO-E Transparency Platform.

## Why this is a parallel star and not a `country` column on the GB tables

The handover note proposed adding a country dimension to `settlement_period`, `price`,
`generation` and `demand`. That was the wrong shape, for four reasons that only became
clear on reading the GB schema against what ENTSO-E actually returns:

1. `settlement_period` is a *GB settlement* calendar. Its `period` column counts 1-48 on
   the local clock, 46 or 50 on clock-change days, and that object does not exist outside
   GB. A country column would leave it meaningless on every row but one country's.
2. `generation` references `fuel`, which carries GB SRMC parameters: QEP gas, Carbon
   Price Support, UK ETS. Those are British tax and market instruments. ENTSO-E
   production types have no relationship with that costing layer.
3. The GB ETL truncates with RESTART IDENTITY, which reassigns every `time_id`. Sharing
   those tables would mean each GB reload silently invalidated European rows that are
   slow and rate-limited to re-fetch. Weather already had to be kept out of that blast
   radius for exactly this reason.
4. The grains differ: GB is half-hourly, ENTSO-E hourly.

So the two live side by side in one database, sharing `gbmo.arbitrage` (which takes a
price vector and a battery spec and knows nothing about any country) but not the GB
costing layer, which stays explicitly British.

Revision ID: b91c4a7d2e05
Revises: a305783f9fcc
Create Date: 2026-09-05
"""

from alembic import op

revision = "b91c4a7d2e05"
down_revision = "a305783f9fcc"
